package wired

import (
	"bytes"
	"testing"
)

// Covers: SIG-IPE-310
func FuzzParse(f *testing.F) {
	f.Add([]byte{0x68, 0x1f, 0x1f, 0x68, 0x08, 0x02, 0x72, 0x78, 0x56, 0x34, 0x12, 0x24, 0x40, 0x01, 0x07, 0x55, 0x00, 0x00, 0x00,
		0x03, 0x13, 0x15, 0x31, 0x00, 0xda, 0x02, 0x3b, 0x13, 0x01, 0x8b, 0x60, 0x04, 0x37, 0x18, 0x02, 0x18, 0x16})
	f.Add([]byte{0x10, 0x40, 0x01, 0x41, 0x16})
	f.Fuzz(func(t *testing.T, b []byte) {
		fr, err := ReadFrame(bytes.NewReader(b))
		if err != nil {
			return
		}
		_, _ = ParseResponse(fr)
		if fr.Long && len(fr.Data) >= 8 {
			_ = ParseSecondary(fr.Data).Matches(Wildcard)
		}
	})
}
